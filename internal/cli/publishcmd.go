// newPublishCmd is `para publish <set>`: it writes a publish set to its folder
// on this machine. It is not an op, so no MCP caller can make para write the
// folder; publish preview and publish set are ops. The folder of a set is per
// machine ($PARA_HOME/vaults/<id>/publish.json), set with publish dir.
func newPublishCmd(l *loader) *cobra.Command {
	cmd := &cobra.Command{
		Use:   "publish <set>",
		Short: "Write a publish set to its folder on this machine, as plain markdown (the owner only)",
		Long: `Write every document whose publish lists <set> to the set's folder on this
machine, as plain markdown: one file per document and an index.md. A wikilink
to a document of the set becomes a relative link; any other becomes plain
text. An embed or block reference of a document outside the set refuses the
run, and nothing is written.

The folder is replaced in full every run: a document taken out of the set
disappears. Para refuses a folder that holds files it did not write (each
file it writes starts with a "Generated by para publish" line). The people,
groups, and io items the documents link are listed for you to check before you
share the folder. One egress event is logged per run (ids and hashes only).

  para publish set <id> <set>...   put a document in sets (no sets: take it out)
  para publish dir <set> <path>    the set's folder on this machine
  para publish preview <set>       what a run would write
  para vault config set publish.<set>.marking "TEXT"   banner (default: classification)`,
		Args: cobra.ExactArgs(1),
		RunE: func(cmd *cobra.Command, args []string) error {
			return publishRun(cmd, l, args[0])
		},
	}
	cmd.AddCommand(newPublishSetCmd(l), newPublishPreviewCmd(l), newPublishDirCmd(l))
	return cmd
}

func publishRun(cmd *cobra.Command, l *loader, set string) error {
	if err := l.load(); err != nil {
		return err
	}
	if l.agent() {
		return errors.New("publish: only the owner publishes; run it without --actor or PARA_ACTOR")
	}
	deps, err := l.deps()
	if err != nil {
		return err
	}
	s := deps.Store
	if err := publish.CheckSet(set); err != nil {
		return err
	}
	c, err := publish.LoadConfig(s.Info().StateDir)
	if err != nil {
		return err
	}
	sc, ok := c.Sets[set]
	if !ok {
		return fmt.Errorf("publish: set %s has no folder on this machine: para publish dir %s <path>", set, set)
	}
	dir, err := publish.ResolveDir(sc.Dir)
	if err != nil {
		return err
	}
	p, err := publish.Build(cmd.Context(), s, set)
	if err != nil {
		return err
	}
	w := cmd.OutOrStdout()
	if err := writeReview(w, p.Review); err != nil {
		return err
	}
	if err := publish.Publish(cmd.Context(), s, p, dir); err != nil {
		return err
	}
	_, err = fmt.Fprintf(w, "wrote %d documents and %s to %s\n", len(p.Files), publish.IndexName, dir)
	return err
}

func writeReview(w io.Writer, review []publish.ReviewItem) error {
	if len(review) == 0 {
		_, err := fmt.Fprintln(w, "review: the documents link no people, groups, or io items")
		return err
	}
	if _, err := fmt.Fprintln(w, "review before you share: the documents link these people, groups, and io items"); err != nil {
		return err
	}
	for _, r := range review {
		if _, err := fmt.Fprintf(w, "  %-7s %s  %s  (from %s)\n", r.Type, r.ID, r.Title, strings.Join(r.From, ", ")); err != nil {
			return err
		}
	}
	return nil
}

func newPublishSetCmd(l *loader) *cobra.Command {
	return opCommand(l, ops.PublishSet, binding[ops.PublishSetInput, ops.PublishSetOutput]{
		Use:  "set <id> [<set>...]",
		Args: cobra.MinimumNArgs(1),
		Bind: func(args []string, in *ops.PublishSetInput) error {
			in.ID, in.Sets = args[0], args[1:]
			return nil
		},
		Text: func(w io.Writer, out ops.PublishSetOutput) error {
			if len(out.Publish) == 0 {
				_, err := fmt.Fprintf(w, "%s is in no publish set\n", out.ID)
				return err
			}
			_, err := fmt.Fprintf(w, "%s publish: %s\n", out.ID, strings.Join(out.Publish, ", "))
			return err
		},
	})
}

func newPublishPreviewCmd(l *loader) *cobra.Command {
	return opCommand(l, ops.PublishPreview, binding[ops.PublishPreviewInput, ops.PublishPreviewOutput]{
		Use:  "preview <set>",
		Args: cobra.ExactArgs(1),
		Bind: func(args []string, in *ops.PublishPreviewInput) error {
			in.Set = args[0]
			return nil
		},
		Text: func(w io.Writer, out ops.PublishPreviewOutput) error {
			say := func(format string, a ...any) { _, _ = fmt.Fprintf(w, format+"\n", a...) }
			if len(out.Files) == 0 {
				say("no document is in set %s", out.Set)
				return nil
			}
			say("set %s, marking %s", out.Set, out.Marking)
			say("files:")
			for _, f := range out.Files {
				say("  %s  %s", f.Name, f.ID)
			}
			if len(out.Rewrites) > 0 {
				say("links:")
				for _, r := range out.Rewrites {
					say("  %s -> %s: %s", r.Doc, r.Target, r.To)
				}
			}
			for _, r := range out.Refused {
				say("refused: %s %s %s, which is not in the set", r.Doc, r.Why, r.Target)
			}
			return writeReview(w, out.Review)
		},
	})
}

// newPublishDirCmd sets, shows, or clears a set's folder on this machine. It
// is not an op: the path is this machine's, and no agent surface sets it.
func newPublishDirCmd(l *loader) *cobra.Command {
	var clearDir bool
	cmd := &cobra.Command{
		Use:   "dir <set> [<path>]",
		Short: "Set or show the folder of a publish set on this machine (absolute, or under ~/); --clear removes it",
		Args:  cobra.RangeArgs(1, 2),
		RunE: func(cmd *cobra.Command, args []string) error {
			if err := l.load(); err != nil {
				return err
			}
			sel, err := l.selectVault()
			if err != nil {
				return err
			}
			state := l.stateDir(sel.ID)
			set, w := args[0], cmd.OutOrStdout()
			if err := publish.CheckSet(set); err != nil {
				return err
			}
			if len(args) == 1 && !clearDir {
				c, err := publish.LoadConfig(state)
				if err != nil {
					return err
				}
				if sc, ok := c.Sets[set]; ok {
					_, err = fmt.Fprintln(w, sc.Dir)
					return err
				}
				return fmt.Errorf("publish: set %s has no folder on this machine", set)
			}
			if l.agent() {
				return errors.New("publish: only the owner sets a publish folder; run it without --actor or PARA_ACTOR")
			}
			if clearDir {
				if len(args) == 2 {
					return errors.New("publish dir: --clear takes no path")
				}
				return publish.SaveDir(state, set, "")
			}
			if err := publish.SaveDir(state, set, args[1]); err != nil {
				return err
			}
			_, err = fmt.Fprintf(w, "set %s publishes to %s on this machine\n", set, args[1])
			return err
		},
	}
	cmd.Flags().BoolVar(&clearDir, "clear", false, "remove the set's folder on this machine")
	return cmd
}
