// Package publish writes a set of vault documents to a folder on this
// machine as plain markdown, for readers that do not run para (para publish
// <set>). A document is in a set when its frontmatter publish lists the set;
// only the owner sets that field (ops.PublishSet).
//
// The folder is written in full every run: a file per document, an index, and
// nothing else. A run is refused, with nothing written, when a document of
// the set embeds or block-references a document outside it. Para never
// deletes a file it did not write: a folder that holds one is refused.
package publish

import (
	"cmp"
	"context"
	"crypto/sha256"
	"encoding/hex"
	"errors"
	"fmt"
	"regexp"
	"slices"
	"strings"
	"time"

	"github.com/iodesystems/para/internal/egress"
	"github.com/iodesystems/para/internal/export"
	"github.com/iodesystems/para/internal/model"
	"github.com/iodesystems/para/internal/store"
)

// HeaderPrefix starts the first line of every file para publish writes. A
// file in the folder without it is not para's.
const HeaderPrefix = "> Generated by para publish "

// IndexName is the index file of a published folder.
const IndexName = "index.md"

var (
	setRe   = regexp.MustCompile(`^[a-z][a-z0-9_-]{0,47}$`)
	nonSlug = regexp.MustCompile(`[^a-z0-9]+`)
)

// Reserved are set names that are subcommands of para publish.
var Reserved = []string{"set", "preview", "dir"}

// CheckSet refuses a set name that is not a plain lower-case word.
func CheckSet(name string) error {
	if !setRe.MatchString(name) {
		return fmt.Errorf("publish: set %q: want a lower-case word of letters, digits, - and _ (at most 48)", name)
	}
	if slices.Contains(Reserved, name) {
		return fmt.Errorf("publish: set %q: the name is a para publish command; pick another", name)
	}
	return nil
}

// MarkingKey is the vault setting with a set's banner text.
func MarkingKey(set string) string { return "publish." + set + ".marking" }

// Dest is the egress destination of a set.
func Dest(set string) string { return egress.DestPublish + set }

// File is one file of a published folder.
type File struct {
	ID    string `json:"id"` // the document; empty for the index
	Title string `json:"title"`
	Name  string `json:"name"` // file name in the folder
	Hash  string `json:"hash"` // sha256:<hex> of Data
	Data  []byte `json:"-"`
}

// Rewrite is a wikilink of a document and the text the published file has.
type Rewrite struct {
	Doc    string `json:"doc"`
	Target string `json:"target"`
	InSet  bool   `json:"in_set"` // a relative link to the target's file; else plain text
	To     string `json:"to"`
}

// ReviewItem is a person, group, or io item a document of the set links. The
// owner checks these names before sharing the folder.
type ReviewItem struct {
	ID    string   `json:"id"`
	Type  string   `json:"type"`
	Title string   `json:"title"`
	From  []string `json:"from"` // documents of the set that link it
}

// Refusal is an embed or block reference of a document outside the set.
type Refusal struct {
	Doc    string `json:"doc"`
	Target string `json:"target"`
	Why    string `json:"why"`
}

// Plan is a run of a set, rendered in memory.
type Plan struct {
	Set      string       `json:"set"`
	Vault    string       `json:"vault"`
	Date     string       `json:"date"`
	Marking  string       `json:"marking"`
	Files    []File       `json:"files"` // one per document, by id
	Index    File         `json:"index"`
	Rewrites []Rewrite    `json:"rewrites"`
	Review   []ReviewItem `json:"review"`
	Refused  []Refusal    `json:"refused"`
}

// reviewTypes are the types the review list names.
var reviewTypes = []model.Type{model.TypePerson, model.TypeGroup, model.TypeTeam, model.TypeRole, model.TypeDomain, model.TypeIO}

// Build finds the documents of set and renders each one. It writes nothing
// and logs nothing. A set with no document has no files (Err refuses it).
func Build(ctx context.Context, s store.Store, set string) (Plan, error) {
	if err := CheckSet(set); err != nil {
		return Plan{}, err
	}
	cfg, err := s.ConfigAll()
	if err != nil {
		return Plan{}, fmt.Errorf("publish: build: %w", err)
	}
	p := Plan{Set: set, Vault: s.VaultID(), Date: s.Now().Format(time.DateOnly), Marking: strings.TrimSpace(cfg[MarkingKey(set)]),
		Files: []File{}, Rewrites: []Rewrite{}, Review: []ReviewItem{}, Refused: []Refusal{}}
	if p.Marking == "" {
		p.Marking = egress.Check(cfg, Dest(set)).Marking
	}
	refs, err := s.List(ctx, store.Filter{})
	if err != nil {
		return Plan{}, fmt.Errorf("publish: build: %w", err)
	}
	var docs []model.Document
	name := map[string]string{}
	for _, r := range refs {
		doc, err := s.Get(ctx, r.ID)
		if err != nil {
			return Plan{}, fmt.Errorf("publish: build: %w", err)
		}
		if slices.Contains(doc.Meta.Header().Publish, set) {
			docs = append(docs, doc)
			name[doc.ID] = FileName(doc.ID, doc.Title)
		}
	}
	header := fmt.Sprintf("%s%s from vault %s on %s. Edit the source in the vault, not this file.\n\n", HeaderPrefix, set, p.Vault, p.Date)
	targets := map[string]*model.Document{}
	resolve := func(id string) *model.Document {
		if t, ok := targets[id]; ok {
			return t
		}
		var t *model.Document
		if doc, err := s.Get(ctx, id); err == nil {
			t = &doc
		}
		targets[id] = t
		return t
	}
	review := map[string]*ReviewItem{}
	for _, doc := range docs {
		seen := map[string]bool{}
		link := func(l export.WikiLink) string {
			id := strings.TrimSpace(l.Target)
			t := resolve(id)
			if t != nil {
				id = t.ID
				if typ := t.Meta.Header().Type; slices.Contains(reviewTypes, typ) {
					it := review[id]
					if it == nil {
						it = &ReviewItem{ID: id, Type: string(typ), Title: t.Title}
						review[id] = it
					}
					if !slices.Contains(it.From, doc.ID) {
						it.From = append(it.From, doc.ID)
					}
				}
			}
			file, in := name[id]
			if !in && (l.Embed || l.Block) {
				why := "embeds"
				if !l.Embed {
					why = "block-references"
				}
				p.Refused = append(p.Refused, Refusal{Doc: doc.ID, Target: id, Why: why})
			}
			out := export.PlainLink(l)
			if in {
				text := cmp.Or(l.Alias, t.Title, id)
				out = "[" + text + "](" + file + ")"
			}
			if key := id + "\x00" + out; !seen[key] {
				seen[key] = true
				p.Rewrites = append(p.Rewrites, Rewrite{Doc: doc.ID, Target: id, InSet: in, To: out})
			}
			return out
		}
		data := []byte(header + export.Markdown(doc, p.Marking, link))
		p.Files = append(p.Files, File{ID: doc.ID, Title: doc.Title, Name: name[doc.ID], Hash: hashOf(data), Data: data})
	}
	for _, it := range review {
		p.Review = append(p.Review, *it)
	}
	slices.SortFunc(p.Review, func(a, b ReviewItem) int { return cmp.Or(cmp.Compare(a.Type, b.Type), cmp.Compare(a.ID, b.ID)) })
	p.Index = index(p, header)
	return p, nil
}

// index lists the documents of the set by title.
func index(p Plan, header string) File {
	files := slices.Clone(p.Files)
	slices.SortFunc(files, func(a, b File) int { return cmp.Or(cmp.Compare(a.Title, b.Title), cmp.Compare(a.ID, b.ID)) })
	banner := "**[" + p.Marking + "]**"
	var b strings.Builder
	b.WriteString(header + banner + "\n\n# " + p.Set + "\n\n")
	for _, f := range files {
		b.WriteString("- [" + f.Title + "](" + f.Name + ")\n")
	}
	b.WriteString("\n" + banner + "\n")
	data := []byte(b.String())
	return File{Title: p.Set, Name: IndexName, Hash: hashOf(data), Data: data}
}

// FileName is a document's file in the folder: the slug of its title and a
// short hash of its id, so it stays the same while the title does.
func FileName(id, title string) string {
	s := strings.Trim(nonSlug.ReplaceAllString(strings.ToLower(title), "-"), "-")
	if len(s) > 60 {
		s = strings.TrimRight(s[:60], "-")
	}
	if s == "" {
		s = "doc"
	}
	sum := sha256.Sum256([]byte(id))
	return s + "-" + hex.EncodeToString(sum[:])[:8] + ".md"
}

// Err is the refusal of a plan with no document, or one that embeds or
// block-references a document outside the set, naming each; else nil.
func (p Plan) Err() error {
	if len(p.Files) == 0 {
		return fmt.Errorf("publish: nothing written: no document is in set %s: add one with para publish set <id> %s", p.Set, p.Set)
	}
	if len(p.Refused) == 0 {
		return nil
	}
	lines := make([]string, len(p.Refused))
	for i, r := range p.Refused {
		lines[i] = fmt.Sprintf("  %s %s %s, which is not in the set", r.Doc, r.Why, r.Target)
	}
	return errors.New("publish: nothing written: a document of set " + p.Set + " depends on a document outside it; add that document to the set, or change the link to a plain one:\n" + strings.Join(lines, "\n"))
}

// Manifest is the run's document ids and content hashes, one per line, and
// its hash. It holds no content.
func (p Plan) Manifest() ([]byte, string) {
	var b strings.Builder
	for _, f := range p.Files {
		b.WriteString(f.ID + " " + f.Hash + "\n")
	}
	b.WriteString(IndexName + " " + p.Index.Hash + "\n")
	data := []byte(b.String())
	return data, hashOf(data)
}

// Publish writes a built plan to dir. It refuses a plan with refusals, a dir
// inside the vault, and a dir that holds files para did not write; then logs
// one egress event (the set, and the hash of the manifest of ids and content
// hashes), replaces the folder, and keeps the manifest on this machine.
func Publish(ctx context.Context, s store.Store, p Plan, dir string) error {
	if err := p.Err(); err != nil {
		return err
	}
	if _, err := s.DocAt(ctx, dir); !errors.Is(err, store.ErrOutsideVault) {
		return fmt.Errorf("publish: nothing written: %s is inside the vault; pick a folder outside it", dir)
	}
	if err := CheckDir(dir); err != nil {
		return err
	}
	cfg, err := s.ConfigAll()
	if err != nil {
		return fmt.Errorf("publish: %w", err)
	}
	manifest, hash := p.Manifest()
	d, err := egress.LogRun(ctx, cfg, s.Record, p.Set, Dest(p.Set), hash)
	if err != nil {
		return fmt.Errorf("publish: %w", err)
	}
	if !d.Allowed {
		return fmt.Errorf("publish: nothing written: egress to %s is denied", Dest(p.Set))
	}
	if err := Write(dir, p); err != nil {
		return err
	}
	return SaveManifest(s.Info().StateDir, p.Set, manifest)
}

func hashOf(data []byte) string {
	sum := sha256.Sum256(data)
	return "sha256:" + hex.EncodeToString(sum[:])
}
