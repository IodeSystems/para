// Package service renders para's per-user service: a systemd user unit on
// Linux, a LaunchAgent on macOS (CLI-10). It writes definitions and starts no
// process; the CLI runs the service manager.
package service

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// DefaultName is the unit name, without a suffix.
const DefaultName = "para"

// LabelPrefix namespaces the launchd label.
const LabelPrefix = "com.iodesystems."

// Unit describes the service.
type Unit struct {
	Name       string   // unit name without suffix
	Exec       string   // absolute path of the para binary
	Args       []string // arguments to `para serve`
	WorkingDir string
	Env        []string // KEY=VALUE
}

// UnitFileName is the systemd file name.
func (u Unit) UnitFileName() string { return u.Name + ".service" }

// Label is the launchd label.
func (u Unit) Label() string { return LabelPrefix + u.Name }

// PlistFileName is the launchd file name.
func (u Unit) PlistFileName() string { return u.Label() + ".plist" }

// UserUnitDir is where systemd reads per-user units.
func UserUnitDir(home string) string { return filepath.Join(home, ".config", "systemd", "user") }

// LaunchAgentsDir is where launchd reads per-user jobs.
func LaunchAgentsDir(home string) string { return filepath.Join(home, "Library", "LaunchAgents") }

// LogPath is the log file of a LaunchAgent. launchd has no journal.
func LogPath(home, name string) string {
	return filepath.Join(home, "Library", "Logs", "para", name+".log")
}

// quote renders one argument for a systemd Exec line. systemd does its own
// unquoting: a space makes two arguments, and a bare % is a specifier.
func quote(s string) string {
	if s != "" && !strings.ContainsAny(s, " \t\"'\\$%") {
		return s
	}
	r := strings.NewReplacer(`\`, `\\`, `"`, `\"`, `%`, `%%`, `$`, `$$`)
	return `"` + r.Replace(s) + `"`
}

func execLine(args ...string) string {
	parts := make([]string, len(args))
	for i, a := range args {
		parts[i] = quote(a)
	}
	return strings.Join(parts, " ")
}

// Render produces the systemd unit. ExecStartPre runs `para serve --check` with
// the same flags, so a bad flag stops the unit once with a reason, not in a
// Restart=on-failure loop.
func (u Unit) Render() string {
	var b strings.Builder
	b.WriteString("# Generated by `para service install`. Edits are overwritten on reinstall.\n")
	b.WriteString("[Unit]\nDescription=para server\nAfter=default.target\n\n[Service]\nType=simple\n")
	fmt.Fprintf(&b, "ExecStartPre=%s\n", execLine(append([]string{u.Exec, "serve", "--check"}, u.Args...)...))
	fmt.Fprintf(&b, "ExecStart=%s\n", execLine(append([]string{u.Exec, "serve"}, u.Args...)...))
	if u.WorkingDir != "" {
		fmt.Fprintf(&b, "WorkingDirectory=%s\n", quote(u.WorkingDir))
	}
	for _, e := range u.Env {
		fmt.Fprintf(&b, "Environment=%s\n", quote(e))
	}
	b.WriteString("TimeoutStopSec=15\nRestart=on-failure\nRestartSec=2\n\n[Install]\nWantedBy=default.target\n")
	return b.String()
}

func xmlEscape(s string) string {
	return strings.NewReplacer("&", "&amp;", "<", "&lt;", ">", "&gt;", `"`, "&quot;", "'", "&apos;").Replace(s)
}

// RenderPlist produces the LaunchAgent. launchd has no ExecStartPre, so the
// check runs at install only. KeepAlive.SuccessfulExit=false is
// Restart=on-failure.
func (u Unit) RenderPlist(logPath string) string {
	var b strings.Builder
	b.WriteString(`<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!-- Generated by para service install. Edits are overwritten on reinstall. -->
<plist version="1.0">
<dict>
`)
	kv := func(k, v string) { fmt.Fprintf(&b, "\t<key>%s</key>\n\t<string>%s</string>\n", k, xmlEscape(v)) }
	kv("Label", u.Label())
	b.WriteString("\t<key>ProgramArguments</key>\n\t<array>\n")
	for _, a := range append([]string{u.Exec, "serve"}, u.Args...) {
		fmt.Fprintf(&b, "\t\t<string>%s</string>\n", xmlEscape(a))
	}
	b.WriteString("\t</array>\n")
	if u.WorkingDir != "" {
		kv("WorkingDirectory", u.WorkingDir)
	}
	if len(u.Env) > 0 {
		b.WriteString("\t<key>EnvironmentVariables</key>\n\t<dict>\n")
		for _, e := range u.Env {
			k, v, _ := strings.Cut(e, "=")
			kv(k, v)
		}
		b.WriteString("\t</dict>\n")
	}
	kv("StandardOutPath", logPath)
	kv("StandardErrorPath", logPath)
	b.WriteString("\t<key>RunAtLoad</key>\n\t<true/>\n")
	b.WriteString("\t<key>KeepAlive</key>\n\t<dict>\n\t\t<key>SuccessfulExit</key>\n\t\t<false/>\n\t</dict>\n")
	b.WriteString("\t<key>ThrottleInterval</key>\n\t<integer>10</integer>\n\t<key>ExitTimeOut</key>\n\t<integer>15</integer>\n")
	b.WriteString("</dict>\n</plist>\n")
	return b.String()
}

// Install writes content to dir/file and returns the path.
func Install(dir, file, content string) (string, error) {
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return "", fmt.Errorf("service: install: %w", err)
	}
	p := filepath.Join(dir, file)
	if err := os.WriteFile(p, []byte(content), 0o644); err != nil {
		return "", fmt.Errorf("service: install: %w", err)
	}
	return p, nil
}

// ExecArgs reads the `para serve` arguments back from an installed unit or
// plist. It reports false when the file is unreadable.
func ExecArgs(file string) ([]string, bool) {
	b, err := os.ReadFile(file)
	if err != nil {
		return nil, false
	}
	text := string(b)
	if strings.HasSuffix(file, ".plist") {
		var out []string
		_, rest, ok := strings.Cut(text, "<array>")
		if !ok {
			return nil, false
		}
		arr, _, _ := strings.Cut(rest, "</array>")
		for _, line := range strings.Split(arr, "\n") {
			line = strings.TrimSpace(line)
			if v, ok := strings.CutPrefix(line, "<string>"); ok {
				out = append(out, strings.TrimSuffix(v, "</string>"))
			}
		}
		return out, true
	}
	for _, line := range strings.Split(text, "\n") {
		if v, ok := strings.CutPrefix(line, "ExecStart="); ok {
			return strings.Fields(strings.ReplaceAll(v, `"`, "")), true
		}
	}
	return nil, false
}

// EnvValue reads one Environment value back from an installed unit or plist.
func EnvValue(file, key string) string {
	b, err := os.ReadFile(file)
	if err != nil {
		return ""
	}
	lines := strings.Split(string(b), "\n")
	for i, line := range lines {
		line = strings.TrimSpace(line)
		if v, ok := strings.CutPrefix(strings.ReplaceAll(line, `"`, ""), "Environment="+key+"="); ok {
			return v
		}
		if line == "<key>"+key+"</key>" && i+1 < len(lines) {
			v := strings.TrimSpace(lines[i+1])
			return strings.TrimSuffix(strings.TrimPrefix(v, "<string>"), "</string>")
		}
	}
	return ""
}

// FlagValue returns the value of --name or --name=value in args.
func FlagValue(args []string, name string) string {
	for i, a := range args {
		if a == name && i+1 < len(args) {
			return args[i+1]
		}
		if v, ok := strings.CutPrefix(a, name+"="); ok {
			return v
		}
	}
	return ""
}
