package server

import (
	"github.com/iodesystems/para/internal/netguard"
	"github.com/iodesystems/para/internal/ops"
)

// registerLife: areas, notes, incidents, meetings, questions, links, and dependency edits. Reads are GET with
// vault:read, writes POST with vault:write.
func registerLife(r *registrar) {
	scopeOnly(r, ops.AreaAdd, write)
	reg(r, ops.AreaList, get, read)
	scopeOnly(r, ops.AreaShow, read)
	reg(r, ops.AreaReview, post, write)
	reg(r, ops.NoteAdd, post, write)
	scopeOnly(r, ops.NoteEdit, write)
	reg(r, ops.DocEdit, post, write)
	reg(r, ops.DocRename, post, write)
	reg(r, ops.DocRetype, post, write)
	reg(r, ops.DocMerge, post, write)
	reg(r, ops.DocArchive, post, write)
	reg(r, ops.DocMerges, get, read)
	reg(r, ops.NotesRead, get, read)
	reg(r, ops.NotesEdit, post, write)
	reg(r, ops.NotesSave, post, netguard.ScopeReviewDecide)
	reg(r, ops.TaskMove, post, write)
	reg(r, ops.RFXNudge, post, write)
	reg(r, ops.AttemptAdd, post, write)
	reg(r, ops.NoteList, get, read)
	scopeOnly(r, ops.NoteShow, read)
	reg(r, ops.AreaLinkAdd, post, write)
	reg(r, ops.AreaLinkRemove, post, write)
	reg(r, ops.GoalLinkAdd, post, write)
	reg(r, ops.GoalLinkRemove, post, write)
	reg(r, ops.Where, get, read)
	scopeOnly(r, ops.IncidentAdd, write)
	reg(r, ops.IncidentList, get, read)
	scopeOnly(r, ops.IncidentShow, read)
	reg(r, ops.IncidentNote, post, write)
	reg(r, ops.IncidentStatus, post, write)
	reg(r, ops.IncidentLinkAdd, post, write)
	reg(r, ops.IncidentLinkRemove, post, write)
	reg(r, ops.QuestionAdd, post, write)
	reg(r, ops.QuestionList, get, read)
	scopeOnly(r, ops.QuestionShow, read)
	reg(r, ops.QuestionAnswer, post, write)
	scopeOnly(r, ops.QuestionDrop, write)
	// owner 2026-11-06: Investigate next to Done in the web app, on the
	// owner's session (review:decide), as close does.
	reg(r, ops.Investigate, post, netguard.ScopeReviewDecide)
	scopeOnly(r, ops.Defer, write)
	scopeOnly(r, ops.Undefer, write)
	reg(r, ops.DependsCut, post, write)
	reg(r, ops.DependsSet, post, write)
	reg(r, ops.OrderOp, get, read)
	reg(r, ops.HealthOp, get, read)
	reg(r, ops.HealthDismiss, post, write)
	reg(r, ops.HealthUndismiss, post, write)
	scopeOnly(r, ops.QuestionEdit, write)
	reg(r, ops.QuestionDependsAdd, post, write)
	reg(r, ops.QuestionDependsRemove, post, write)
	reg(r, ops.QuestionAsk, post, write)
	scopeOnly(r, ops.MeetingAdd, write)
	reg(r, ops.MeetingList, get, read)
	reg(r, ops.MeetingShow, get, read)
	reg(r, ops.Brief, get, read)
	scopeOnly(r, ops.MeetingSchedule, write)
	scopeOnly(r, ops.MeetingCancel, write)
	scopeOnly(r, ops.MeetingHold, write)
	scopeOnly(r, ops.MeetingAttend, write)
	reg(r, ops.MeetingRSVP, post, netguard.ScopeReviewDecide)
	// owner 2026-11-06: PU-REC. The web form New recurring artifact makes an
	// obligation on the owner's session (review:decide), as close does.
	reg(r, ops.ObligationAdd, post, netguard.ScopeReviewDecide)
	reg(r, ops.ObligationSchedule, post, write)
	// owner 2026-11-06: OB. Push out, Redirect, and Cancel on the obligation
	// page and its rows, on the owner's session (review:decide); the notices
	// it writes are drafts the owner approves.
	reg(r, ops.ObligationChange, post, netguard.ScopeReviewDecide)
	reg(r, ops.ObligationParts, get, read)
	reg(r, ops.ObligationTimeline, get, read)
	reg(r, ops.ObligationAttend, post, write)
	reg(r, ops.Agenda, get, read)
	reg(r, ops.TaskToQuestion, post, write)
	reg(r, ops.TaskDue, post, write)
	scopeOnly(r, ops.TaskEdit, write)
	reg(r, ops.ItemPrepared, post, write)
	reg(r, ops.TaskDependsAdd, post, write)
	reg(r, ops.TaskDependsRemove, post, write)
}
